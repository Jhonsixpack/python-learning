#OPERADORES DE ASIGNACIÓN

a = 5
b = 3

# Igual a 
c = a == b
print(f"a == b = {c}")
#Pasa a ser True si a es igual a b, de lo contrario pasa a ser False
#--------------------------------------------

# NO igual a

c = a != b
print(f"a != b = {c}")
#Pasa a ser True si a es diferente a b, de lo contrario pasa a ser False

#--------------------------------------------

# Mayor que

c = a > b
print(f"a > b = {c}")
#Pasa a ser True si a es mayor que b, de lo contrario pasa a ser False

#--------------------------------------------

# Menor que

c = a < b
print(f"a < b = {c}")
#Pasa a ser True si a es menor que b, de lo contrario pasa a ser False

#--------------------------------------------

# Mayor o igual que

c = a >= b
print(f"a >= b = {c}")
#Pasa a ser True si a es mayor o igual que b, de lo contrario pasa a ser False

#--------------------------------------------

# Menor o igual que

c = a <= b
print(f"a <= b = {c}")
#Pasa a ser True si a es menor o igual que b, de lo contrario pasa a ser False
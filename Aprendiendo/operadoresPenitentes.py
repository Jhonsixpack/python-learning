## OPERADORES DE PERTINENCIA

# "in" --> Devuelve True si el elemento está en la lista, False si no lo está.
# "not in" --> Devuelve True si el elemento no está en la lista, False si lo está.

a = [1,2,3,4,5]
print(f"a = {a}")

# in
print(f"1 in {a} = {1 in a}")

print(f"6 in {a} = {6 in a}")

# not in 

print(f"1 not in {a} = {1 not in a}")

print(f"6 not in {a} = {6 not in a}")

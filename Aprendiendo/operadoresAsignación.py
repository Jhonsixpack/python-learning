#OPERADORES DE ASIGNACIÓN

#ASIGNACIÓN

a = 5 
print(f"asignación: a = {a}")

#ASIGNACIÓN SUMA
a = 5
a += 3
#originalmente es: a = a + 3
print(f"asignación suma: a += 3 = {a}")

#ASIGNACIÓN RESTA
a = 10
a -= 4
#originalmente es: a = a - 4
print(f"asignación resta: a -= 4 = {a}")

#ASIGNACIÓN MULTIPLICACIÓN
a = 5
a *= 2
#originalmente es: a = a * 2
print(f"asignación multiplicación: a *= 2 = {a}")

#ASIGNACIÓN DIVISIÓN
a = 10
a /= 2
#originalmente es: a = a / 2
print(f"asignación división: a /= 2 = {a}")

#ASIGNACIÓN EXPONENTE
a = 3
b = 2
a **= b
#originalmente es: a = a ** b
print(f"asignación exponente: a **= b = {a}")

#ASIGNACIÓN DIVISIÓN ENTERA
a = 5
a //= 2
#originalmente es: a = a // 2
print(f"asignación división entera: a //= 2 = {a}")

#ASIGNACIÓN RESIDUO
a = 5 
a %= 2
#originalmente es: a = a % 2
print(f"asignación residuo: a %= 2 = {a}")